def story_options(sector, positive):
 index = 0 if positive else 1
 # Existing sober business headlines remain alongside the lighter clan stories.
 reasons = REASONS.get(sector, REASONS['기술'])[index]
 details = ('회사 측은 관련 성과와 후속 계획을 점검하고 있다고 밝혔다.' if positive
            else '회사 측은 원인을 확인하고 대응 계획을 마련하고 있다고 밝혔다.')
 return [(reason, details) for reason in reasons] + STORIES.get(sector, ([], []))[index]


def article(name, sector, old, price, previous=''):
 change = (price - old) * 100 / old
 candidates = NEUTRAL if price == old else story_options(sector, price > old)
 # Exclude the underlying story, not only the exact headline/tail combination.
 candidates = [item for item in candidates if item[0] not in previous] or candidates
 reason, detail = secrets.choice(candidates)
 if price == old:
  return f'[{name}] {reason}', f'{name}의 이번 회차 가격은 {price:,}마리로 유지됐다. {detail}'
 magnitude = abs(change)
 positive = price > old
 if magnitude >= 25:
  tails = (['주가 급등에 게시판 들썩', '주주들 놀란 가슴 쓸어내려', '강한 상승에 시선 집중'] if positive
           else ['주가 급락에 게시판 술렁', '낙폭 커지며 주주들 긴장', '충격에 투자 심리 얼어붙어'])
 elif magnitude >= 10:
  tails = (['상승 폭 키우며 주주들 반색', '주가 탄력에 관심 집중', '주주 게시판에 기대감'] if positive
           else ['낙폭 확대에 주주들 한숨', '주가 약세에 우려 확산', '주주 게시판에 걱정 늘어'])
 else:
  tails = UP if positive else DOWN
 level = ('급등' if magnitude >= 25 else '큰 폭 상승' if magnitude >= 10 else '상승') if positive else ('급락' if magnitude >= 25 else '큰 폭 하락' if magnitude >= 10 else '하락')
 headline = f'[{name}] {reason}…{secrets.choice(tails)}'
 body = f'{name}의 주가가 직전 회차 대비 {magnitude:.2f}% {level}해 {price:,}마리로 갱신됐다. {detail}'
 return headline, body
